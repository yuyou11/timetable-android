package com.yxz.timetable.data

/**
 * 内置**示例**课表 —— 一份虚构的理工科大一课表。
 *
 * 它存在的意义是「让 App 装好之后立刻有东西可看」：第一次启动时可以选
 * 「用示例课表」快速体验，也可以选「从空白开始」导入自己的课表。
 *
 * ⚠️ **这份数据是编的**，课程名和教室号都不是真实存在的院系。
 * 要发给别人用的软件，内置数据必须是无指向性的示例：
 * 内置一份真实课表等于把某个具体的人、某个具体的学校连同作息一起公开出去，
 * 而这份代码是会进公开仓库的。
 *
 * ## 为什么把「周次」存成一个集合，而不是「起始周、结束周、单双周」
 *
 * 课表里出现过四种写法：
 *   「2-4, 6-17 周」  连续段 + 断档
 *   「3, 5, 7, 9 周」  零散单周
 *   「3-17 周·单周」   等差数列
 *   「仅第 4 周」      单点
 *
 * 如果按「起始+结束+单双周」来建模，这四种要写四套判断逻辑，
 * 而且碰到「2-4 周 + 9 周」这种混合情况就没法表达。
 *
 * 换成**直接列举周次集合**，四种写法全都塌缩成同一件事：
 * 「这一周在不在集合里？」——判断只有一行 `week in course.weeks`。
 * 代价只是存了十几个整数，完全不值得为省这点内存去换复杂度。
 *
 * 这是很通用的一个思路：**当规则的种类多于三种时，与其写分支，不如把规则数据化。**
 *
 * 注意这份示例同时保留了上面四种写法（下面每一条的注释里标了），
 * 因为它是用户导入自己课表前最直观的一份「写法范本」。
 */
object BuiltinCourses {

    /** 连续区间 -> 周次集合，例如 r(2..4, 6..17) */
    private fun r(vararg ranges: IntRange): Set<Int> =
        ranges.flatMap { it.toList() }.toSet()

    /** 零散周次 -> 周次集合，例如 s(3, 5, 7, 9) */
    private fun s(vararg weeks: Int): Set<Int> = weeks.toSet()

    val LIST: List<Course> = listOf(

        // ---------------- 周一（A 型日） ----------------
        Course("c01", "大学英语", 1, 1, 2, r(2..4, 6..17), "教一-101"),
        Course("c02", "高等数学", 1, 3, 4, r(2..4, 6..17), "教一-203"),
        Course("c03", "中国近现代史纲要", 1, 5, 6, r(15..17), "教二-105"),
        Course("c04", "军事理论", 1, 7, 8, r(2..4, 6..14), "教二-311"),

        // ---------------- 周二（B 型日 · 力量A） ----------------
        Course("c05", "程序设计基础", 2, 3, 4, r(2..7, 9..17), "实验楼-201"),
        Course("c06", "大学物理实验", 2, 5, 6, s(4), "实验楼-305"),
        Course("c07", "思想道德与法治", 2, 7, 8, r(2..7, 9..17), "教一-108"),

        // ---------------- 周三（A 型日） ----------------
        Course("c08", "高等数学", 3, 1, 2, r(2..7, 9..17), "教一-203"),
        Course("c09", "形势与政策", 3, 3, 4, s(5, 6, 7, 9), "教二-220"),
        Course("c10", "中国近现代史纲要", 3, 7, 8, r(13..17), "教二-105"),
        Course("c11", "人工智能导论", 3, 9, 10, r(3..7, 9..11), "教三-401"),

        // ---------------- 周四（B 型日 · 力量B） ----------------
        Course("c12", "大学物理", 4, 3, 4, r(2..3, 5..17), "教二-108"),
        Course("c13", "大学生职业生涯规划", 4, 5, 6, s(3, 5, 7, 9), "教一-215"),
        // 「3-17 周·单周」：单周就是奇数周，直接列出来
        Course("c14", "数据结构", 4, 7, 8, s(3, 5, 7, 9, 11, 13, 15, 17), "实验楼-201"),
        // 和上面那门**同一时段、不同周次**：第 2 周归这门，第 3 周起归上面那门。
        // 这正是「同格可以放多门课，只要周次不重叠」这个设计的用法示范。
        Course("c15", "程序设计基础", 4, 7, 8, s(2), "实验楼-201"),

        // ---------------- 周五（B 型日） ----------------
        Course("c16", "高等数学", 5, 3, 4, s(2) + r(5..16), "教一-203"),
        Course("c17", "思想道德与法治", 5, 5, 6, s(2) + r(5..12), "教一-108"),
        Course("c18", "大学体育", 5, 7, 8, s(2) + r(5..16), "操场 / 体育馆"),
        Course("c19", "音乐鉴赏", 5, 9, 10, r(5..12), "教三-102")
    )
}
