package com.yxz.timetable.data

/**
 * 「数据生成向导」用的提示词。
 *
 * ## 为什么要把提示词做成程序生成，而不是写死一段文字
 *
 * 提示词里最关键的三个值是**学期名称、第 1 周周一日期、总周数** ——
 * 它们决定了整个课表的时间对不对。如果让 AI 去猜，它大概率会编一个日期，
 * 而错一天的后果是每一周的课都错位。
 *
 * 所以这里直接从 Store 里读出来填进去。用户复制到的提示词**天然带着正确的学期信息**，
 * 不需要他自己填，也就没有填错的机会。
 *
 * 同理，格式说明也内嵌在提示词里 —— AI 不需要知道这个 App 的存在，
 * 读完这段提示词就能产出合规的文件。
 *
 * ## 输出版本为什么是 v4 而不是 v5
 *
 * AI 需要的就是「id 键的模板」（v4 起才有）—— 课表提示词里根本没有日型段，
 * 作息提示词里 AI 也不需要发明 dayTypeConfig（哪天用哪套是用户自己的事）。
 * v4 文件 App 照常导入（旧 dayTypes 段不存在就沿用当前配置），
 * 跟电脑版的提示词保持一致，两台设备给 AI 的输入完全一样。
 */
object AiPrompt {

    /**
     * 七种日型的触发规则。**规则是格式标准的一部分，不会因为用户改名而变** ——
     * id 与「哪天自动用这一套」的对应关系写死在这里，名字才是用户数据。
     */
    private val DAY_TYPE_RULES = mapOf(
        "1" to "工作日第 1-2 节有课（有早八）的那天自动用",
        "2" to "没有早八的普通工作日",
        "3" to "每周二（是否启用由用户的星期映射决定）",
        "4" to "每周四（是否启用由用户的星期映射决定）",
        "5" to "周六",
        "6" to "周日",
        "7" to "工作日全天没课的日子（休息日，可选）"
    )

    /** 提示词里那张表的排列顺序：id 升序（含休息日） */
    private val DAY_TYPE_TABLE_ORDER =
        Templates.ALL_TYPES + DayType.REST

    /** 生成提示词里那张「id → 当前名字 → 触发规则」对照表 */
    private fun dayTypeTable(dayTypeNames: Map<DayType, String>): String =
        DAY_TYPE_TABLE_ORDER.joinToString("\n") { t ->
            "  \"${t.id}\"   ${dayTypeName(t, dayTypeNames)} —— ${DAY_TYPE_RULES.getValue(t.id)}"
        }

    /**
     * 课表提示词。
     *
     * @param termName   学期名称
     * @param startDate  教学第 1 周的周一
     * @param totalWeeks 总周数
     * @param periods    当前的节数信息，AI 要据此决定输出文件里的 periods
     */
    fun forCourses(
        termName: String,
        startDate: String,
        totalWeeks: Int,
        periods: String = ScheduleFormat.DEFAULT_PERIODS
    ): String {
        val nodeLimit = ScheduleFormat.nodeCount(periods)
        return """
你是数据格式转换助手。请把我提供的课程信息转换成下面这个 JSON 格式。

# 输出格式

顶层结构（字段顺序照这个来）：

{
  "format": "timetable",
  "version": 4,
  "periods": "$periods",
  "term": {
    "name": "$termName",
    "startDate": "$startDate",
    "totalWeeks": $totalWeeks
  },
  "courses": [
    {
      "name": "大学英语",
      "dayOfWeek": 1,
      "nodes": [1, 2],
      "weeks": "2-4,6-17",
      "place": "教一-101",
      "teacher": "王雅琴"
    }
  ]
}

# periods 节数信息（重要，先看材料再定）

- 一串数字（1-14 位，每位 1-9），从左到右是当天从早到晚各时段的节数
  （通常是上午、下午、晚上）。**各位之和 = 这所学校一天有多少节**
- 例如 "442" = 上午 4 节、下午 4 节、晚上 2 节（共 10 节）；
  "445" = 上午 4 节、下午 4 节、晚上 5 节（共 13 节）
- 当前值是 "$periods"（共 $nodeLimit 节）。**如果材料里的节次结构和它不一样，必须修改它**
- 各位之和不能超过 14（一天排不下更多 45 分钟的节）
- 课程 nodes 里的节次从 1 开始按顺序对应

# term 段（已经帮你填好，原样保留即可）

- name：学期名称
- startDate：教学第 1 周的**周一**，格式必须是 YYYY-MM-DD
- totalWeeks：总周数，所有 weeks 字段的取值不能超过这个数

# courses 数组，每门课一个对象

- name        课程名，字符串
- dayOfWeek   星期几，1 到 7 的整数（**周一=1**，周日=7）
- nodes       数组 [起始节次, 结束节次]，两个整数，范围 1-$nodeLimit 且起始 ≤ 结束
              连堂课写成 [1, 2]，**不要**拆成两条记录
- weeks       上课周次，字符串，写法见下
- place       教室，字符串；没有就整个省略这个字段
- teacher     任课老师，字符串；没有就整个省略这个字段。
              材料里（课表截图 / Excel 表格）通常写着老师名字，看到了就填上，
              一个字都不要自己编
- enabled     false 表示这门课停开，一般不用写

## weeks 周次写法

  "3"          第 3 周
  "2-4"        第 2 到 4 周
  "3-17/2"     单周：3、5、7、9、11、13、15、17
  "2-16/2"     双周：2、4、6、8、10、12、14、16
  "2-4,6-17"   分段（第 2-4 周，以及第 6-17 周）
  "*"          全学期每周都上
  "3,5,7"      零散列举

如果原始课表写的是「单周」「双周」，请转换成上面的步长写法。

# 节次时间对照（帮助你理解，不要写进 JSON）

第 1 节 08:30-09:15     第 2 节 09:20-10:05
第 3 节 10:25-11:10     第 4 节 11:15-12:00
第 5 节 14:00-14:45     第 6 节 14:50-15:35
第 7 节 15:55-16:40     第 8 节 16:45-17:30
第 9 节 19:00-19:45     第 10 节 19:50-20:35

第 11 节起按晚课节奏外推（每节 45 分钟、间歇 5 分钟、20:40 起始），
最多到第 14 节：

第 11 节 20:40-21:25    第 12 节 21:30-22:15
第 13 节 22:20-23:05    第 14 节 23:10-23:55

「1-2 节」表示第 1 节和第 2 节连堂，nodes 写 [1, 2]。

# 输出要求（重要）

1. **只输出 JSON 本身**。不要写「好的，我来帮你转换」这类开场白，
   不要写解释，不要写总结，不要在末尾加任何说明文字。
2. 不要用 ```json 代码块包起来，直接输出裸的 JSON。
3. 必须是严格合法的 JSON：字符串用双引号，不能有注释，不能有尾随逗号。
4. 中文直接写中文，不要转义成 你好 这种形式。
5. 第一行是 {，最后一行是 }。

# 我提供的材料

（在这里粘贴课表内容，或者直接把课表文件、课表截图拖进来）
""".trimStart()
    }

    /**
     * 作息模板提示词。
     *
     * 模板是「没人管我的时候，我打算怎么过这一天」。
     * 这段提示词比课表那段长很多，因为模板的结构更自由 ——
     * 需要把七种日型、八种时段性质、课表占位格都说清楚。
     *
     * [dayTypeNames] 是用户改过的日型名 —— 表里念**用户认得的名字**，
     * 但要求 AI 输出的键仍然是 id。
     */
    fun forTemplates(
        termName: String,
        periods: String = ScheduleFormat.DEFAULT_PERIODS,
        dayTypeNames: Map<DayType, String> = emptyMap()
    ): String {
        val nodeLimit = ScheduleFormat.nodeCount(periods)
        val table = dayTypeTable(dayTypeNames)
        return """
你是数据格式转换助手。请把我描述的日常作息转换成下面这个 JSON 格式。

（这是给「$termName」用的）

# 输出格式

{
  "format": "timetable",
  "version": 4,
  "courses": [],
  "templates": {
    "1": [
      { "start": "00:00", "end": "06:55", "title": "睡觉", "kind": "SLEEP" },
      { "start": "06:55", "end": "07:10", "title": "起床、洗漱" },
      { "start": "07:10", "end": "07:35", "title": "早餐", "kind": "MEAL" },
      { "start": "08:30", "end": "10:05", "title": "第 1-2 节", "kind": "CLASS", "nodes": [1, 2] }
    ]
  }
}

注意 "courses": [] 是**故意留空**的，表示「只改作息，不动课表」。
程序支持这样导入，不要替我把课程补上。

# templates 段

键是**日型 id**（不是名字）。每种 id 管哪一天由程序自动判定，你不用管；
下面是全部 7 种的当前名字和触发规则：

$table

**你只需要输出我改动过的那几种**，没提到的日型会自动沿用内置模板。
键永远写 id 数字字符串，不要写日型的名字。

# 每一格（block）

  start    开始时刻，字符串 "HH:mm"
  end      结束时刻，字符串 "HH:mm"；一天最后一段可以写 "24:00"
  title    这一格做什么，字符串（必需）
  note     补充说明（可选）
  kind     时段性质（可选，默认 CHORE），取值见下
  nodes    标成「课表格子」（可选），写法 [起始节次, 结束节次]

## kind 的取值

  SLEEP    睡觉（灰蓝）      MEAL     吃饭（橙）
  CLASS    上课/自习课（蓝）  STUDY    自习（紫）
  TRAIN    运动（红）        FREE     自由时间（绿）
  CHORE    洗漱等杂事（青）   TRANSIT  路上（灰）

## nodes 是什么

带 nodes 的格子是**占位符**：当天有课时会被整格替换成课程名和教室，
没课时显示成「第 3-4 节 · 无课」。

如果你希望某个时段由课程自动填充，就给它加上 nodes。
例如上午第 1-2 节、3-4 节、5-6 节、7-8 节、9-10 节这五段，
通常都该是 nodes 占位格，因为它们本来就可能有课。

节次范围是 1-$nodeLimit。「1-2 节」→ nodes: [1, 2]

# 两条硬性规则

1. **同一套模板里，格子之间不能有时间重叠。**
   比如 00:00-08:00 的「睡觉」和 07:00-24:00 的「早起」是冲突的，
   要么改成 08:00 开始，要么把睡觉的结束时间改到 07:00。
2. 尽量让每套模板从 00:00 连续铺到 24:00，中间不要留空。
   留空不是错误，但程序会自动填成「空档 · 机动」，通常不是你想要的。

# 输出要求

1. **只输出 JSON 本身**，不要开场白、不要解释、不要结尾总结。
2. 不要用 ```json 代码块包起来，直接输出裸的 JSON。
3. 严格合法：双引号、无注释、无尾随逗号。
4. 中文直接写中文，不要转义。
5. 第一行是 {，最后一行是 }。

# 我提供的材料

（在这里描述你的作息，例如：
「我早上 6:55 起床，洗漱 15 分钟，7:10 吃早饭，7:35 到 8:15 早读，
8:30 到 10:05 是第 1-2 节课，10:05 到 10:25 是大课间……」
有现成的作息表文件也可以直接上传）
""".trimStart()
    }

    /**
     * 给 AI 的「检查清单」—— 当 AI 输出的东西导入失败时，
     * 可以把这段连同 App 的报错一起发给它，让它自己改。
     */
    fun forFix(errorMessage: String, generatedJson: String): String = """
你刚才生成的时间规划表 JSON 导入失败了，App 报的错是：

---
$errorMessage
---

请修正后重新输出完整的 JSON。注意：

1. 只输出 JSON 本身，不要任何解释文字，不要 ```json 代码块标记
2. 严格合法：字符串用双引号，不能有注释，不能有尾随逗号
3. 检查 weeks 里的周次有没有超出 totalWeeks（当前是 19）
4. 检查 dayOfWeek 是否在 1-7 之间（周一=1）
5. 检查 nodes 是否是两个整数且起始 ≤ 结束，值在 periods 声明的节数范围内
   （默认 "442" 即 1-10）
6. 检查 startDate 是不是周一，格式 YYYY-MM-DD
7. 检查 templates 的键是不是日型 id（"1" 到 "7" 的数字字符串）——
   不是日型名字，也不是数字字面量（键必须带引号）
8. 检查每套模板里格子之间的时间有没有重叠，end 必须晚于 start
9. 检查 periods（如果写了）是不是 1-14 位数字、每位 1-9、各位之和不超过 14
10. 如果写了 dayTypeConfig：weekdayMap 必须恰好 7 项（周一到周日），
    每项 ∈ types 且不能是 "7"（休息日）

你上次生成的 JSON（供参考）：

$generatedJson
""".trimStart()
}
